"""Input: `make install-headers DESTDIR=$PWD/crustify/tmp/hdrs prefix=/usr` run in the plain build.
List deprecated public-API items: decls with DeprecatedAttr, and items that only
exist while FF_API_* is enabled. Output: crustify/wavefront/deprecated.json."""
import json, os, re, shutil, subprocess, collections
cfg = json.load(open("crustify/wavefront/configs/wavefront-config.json"))
API = cfg["api_headers"]
SRC = "crustify/tmp/hdrs/usr/include"            # staged install-headers copy
OFF = "crustify/tmp/hdrs-ffapi-off/usr/include"
shutil.rmtree("crustify/tmp/hdrs-ffapi-off", ignore_errors=True)
shutil.copytree("crustify/tmp/hdrs", "crustify/tmp/hdrs-ffapi-off")
for dp, _, fs in os.walk(OFF):
    for f in fs:
        p = os.path.join(dp, f); t = open(p).read()
        t2 = re.sub(r"^(#define\s+FF_API_\w+)\s+.*$", r"\1 0", t, flags=re.M)
        if t2 != t: open(p, "w").write(t2)

def ast(root):
    tu = "\n".join(f'#include "{h}"' for h in API) + "\n"
    r = subprocess.run(["clang", "-x", "c", "-std=c17", "-fsyntax-only", "-Xclang", "-ast-dump=json",
                        "-I", os.path.abspath(root), "-"], input=tu, capture_output=True, text=True, cwd="/")
    assert r.returncode == 0, r.stderr[-2000:]
    return json.loads(r.stdout)

def items(root):
    """-> {(kind, name[, parent]): {"file":..., "deprecated": bool}} for decls in API headers."""
    out, cur = {}, [None]
    absroot = os.path.abspath(root) + "/"
    def scan(l):
        """Advance the delta-encoded current file over one printed location, in print order."""
        if not isinstance(l, dict): return
        if "spellingLoc" in l or "expansionLoc" in l:
            scan(l.get("spellingLoc")); scan(l.get("expansionLoc")); return
        if "file" in l: cur[0] = l["file"]
    def fileof(n):
        loc = n.get("loc", {})
        if "spellingLoc" in loc or "expansionLoc" in loc:
            scan(loc.get("spellingLoc")); scan(loc.get("expansionLoc"))
            f = cur[0]
        else:
            scan(loc); f = cur[0]
        rng = n.get("range", {})
        scan(rng.get("begin")); scan(rng.get("end"))
        return f
    def rel(f):
        return f[len(absroot):] if f and f.startswith(absroot) else (f[len(root)+1:] if f and f.startswith(root + "/") else None)
    def dep(n): return any(i.get("kind") == "DeprecatedAttr" for i in n.get("inner", []))
    def walk(n, parent=None, pdep=False):
        f = rel(fileof(n)); k = n.get("kind"); name = n.get("name")
        key = None
        if f in API and name and not n.get("isImplicit"):
            if k == "FunctionDecl": key = ("symbol", name)
            elif k == "VarDecl" and parent is None: key = ("symbol", name)
            elif k in ("RecordDecl", "EnumDecl", "TypedefDecl"): key = ("type", name)
            elif k == "FieldDecl" and parent: key = ("field", parent, name)
            elif k == "EnumConstantDecl": key = ("enumerator", parent or "", name)
        if key:
            e = out.setdefault(key, {"file": f, "deprecated": False})
            e["deprecated"] |= dep(n) or (pdep and key[0] in ("field", "enumerator"))
        p = name if k in ("RecordDecl", "EnumDecl") and name else (parent if k not in ("FunctionDecl",) else None)
        for c in n.get("inner", []):
            if isinstance(c, dict): walk(c, p if k in ("RecordDecl", "EnumDecl") else None if k == "TranslationUnitDecl" else parent,
                                         dep(n) if k in ("RecordDecl", "EnumDecl") else False)
    walk(ast(root))
    return out

def macros(root):
    tu = "\n".join(f'#include "{h}"' for h in API) + "\n"
    r = subprocess.run(["clang", "-x", "c", "-E", "-dM", "-I", os.path.abspath(root), "-"], input=tu, capture_output=True, text=True, cwd="/")
    return {m.group(1) for m in re.finditer(r"^#define (\w+)", r.stdout, re.M)}

on, off = items(SRC), items(OFF)
gated = sorted(k for k in on if k not in off)
attr = sorted(k for k, v in on.items() if v["deprecated"])
mgated = sorted(macros(SRC) - macros(OFF))
res = {"_comment": "Deprecated public-API items excluded from this wrap campaign. ff_api_gated: exists only while FF_API_* is enabled; attribute_deprecated: carries DeprecatedAttr. Generated by crustify/wavefront/scripts/deprecated.py from the staged install-headers of the plain build.",
       "ff_api_gated": [list(k) + [on[k]["file"]] for k in gated],
       "attribute_deprecated": [list(k) + [on[k]["file"]] for k in attr],
       "ff_api_gated_macros": mgated}
json.dump(res, open("crustify/wavefront/deprecated.json", "w"), indent=1)
c = collections.Counter(k[0] for k in set(gated) | set(attr))
print("gated", len(gated), "attr", len(attr), "macros", len(mgated), dict(c))
